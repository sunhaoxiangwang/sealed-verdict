import assert from "node:assert/strict";
import { initNode, verifyCert } from "../../packages/protocol/js/node.js";
const base = process.env.AML_URL || "http://127.0.0.1:8090";
const response = await fetch(`${base}/api/aml`);
assert(response.ok, "AML service must be available");
const data = await response.json();
assert.equal(data.run?.status, "complete", JSON.stringify(data.run));
assert.equal(data.input.dataKind, "public_enforcement_record");
assert.equal(data.bundle.cert.body.quorum.counted, 4);
assert.equal(data.run.stats.intentErrors, 0);
assert.equal(data.run.stats.rejected, 0);
assert.deepEqual(new Set(data.run.events.filter(e => e.provider).map(e => e.provider)), new Set(["anthropic", "gemini", "openai"]));
await initNode();
assert.deepEqual(verifyCert(data.bundle), { valid: true, failures: [] });
const tampered = structuredClone(data.bundle);
tampered.transcript.find(e => e.kind === "argument").msg.body.text += " [edited]";
assert.equal(verifyCert(tampered).valid, false);
assert((await fetch(base)).ok, "Built frontend must be served by the workflow API");
console.log(JSON.stringify({ caseId: data.run.caseId, verdict: data.bundle.cert.body.verdict, ballots: 4, terse: data.terseMode, verification: "PASS", tamper: "REJECTED" }, null, 2));
process.exit(0);
